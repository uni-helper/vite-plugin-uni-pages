import type { CommentArray, CommentLineToken, CommentObject } from 'comment-json'
import { CommentArray as CommentArrayValue } from 'comment-json'
import { describe, expect, it } from 'vitest'
import { mergePlatformItems } from '../packages/core/src/pages-json-items'
import { lineComment } from '../packages/core/src/pages-json-tokens'
import { GENERATION_MARKER_PREFIX } from '../packages/core/src/platform-variants'

// comment-json 的注释挂在 Symbol.for('before:i') / ('after:i') 上，
// 类型声明里没有这个索引签名，测试里通过 any 访问
function setComments(items: CommentArray<CommentObject>, key: string, comments: CommentLineToken[]): void {
  const target = items as any
  target[Symbol.for(key)] = comments
}

function commentsAt(items: CommentArray<CommentObject>, key: string): string[] {
  const comments = (items as any)[Symbol.for(key)] as CommentLineToken[] | undefined
  return (comments ?? []).map(comment => comment.value)
}

function sourceWithMarker(platform: string, items: object[] = []): CommentArray<CommentObject> {
  const source = new CommentArrayValue<CommentObject>()
  setComments(source, 'before:0', [lineComment(` ${GENERATION_MARKER_PREFIX} ${platform}`)])
  source.push(...items as CommentObject[])
  return source
}

describe('pages.json 数组适配器', () => {
  it('内容相同的条目把当前平台叠进已有变体，输出不额外包裹', () => {
    const source = sourceWithMarker('H5', [{ path: 'pages/index' }])

    const merged = mergePlatformItems(source, 'MP-WEIXIN', [{ path: 'pages/index' }], 'path')

    expect(merged.items.map(item => item.path)).toEqual(['pages/index'])
    expect(merged.platformUnion).toEqual(['H5', 'MP-WEIXIN'])
    expect(merged.owningPlatforms).toEqual(['H5', 'MP-WEIXIN'])
    expect(commentsAt(merged.items, 'before:0').some(value => value.includes('GENERATED BY UNI-PAGES'))).toBe(true)
    expect(commentsAt(merged.items, 'before:0').some(value => value.includes('#ifdef'))).toBe(false)
  })

  it('内容不同的条目各自保留 #ifdef 变体', () => {
    const source = sourceWithMarker('H5', [{ path: 'pages/index', style: { navigationBarTitleText: 'H5' } }])

    const merged = mergePlatformItems(source, 'MP-WEIXIN', [
      { path: 'pages/index', style: { navigationBarTitleText: '微信' } },
    ], 'path')

    expect(merged.items).toHaveLength(2)
    expect(merged.owningPlatforms).toEqual(['H5', 'MP-WEIXIN'])
    expect(commentsAt(merged.items, 'before:0')).toContain(' #ifdef H5')
    expect(commentsAt(merged.items, 'before:1')).toContain(' #ifdef MP-WEIXIN')
  })

  it('手写 #ifndef 块原样保留，不并入当前平台', () => {
    const source = sourceWithMarker('H5', [{ path: 'pages/manual' }])
    setComments(source, 'before:0', [
      lineComment(` ${GENERATION_MARKER_PREFIX} H5`),
      lineComment(' #ifndef MP-WEIXIN'),
      lineComment(' 手写说明'),
    ])

    const merged = mergePlatformItems(source, 'MP-WEIXIN', [], 'path')

    expect(merged.items.map(item => item.path)).toEqual(['pages/manual'])
    expect(commentsAt(merged.items, 'before:0')).toEqual(expect.arrayContaining([
      ' #ifndef MP-WEIXIN',
      ' 手写说明',
    ]))
    expect(commentsAt(merged.items, 'after:0')).toEqual([' #endif'])
  })
})
