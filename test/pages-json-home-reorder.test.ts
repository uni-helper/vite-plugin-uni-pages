import type { CommentObject } from 'comment-json'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { parse as cjParse } from 'comment-json'
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest'
import { PageContext } from '../packages/core/src'

/**
 * writePagesJson 中首页重排的回归测试。
 *
 * 当首页条目在合并后的数组中不在首位时，三个既有缺陷叠加起来破坏
 * pages.json：
 *
 * 1. `CommentArray#splice`/`unshift` 只挪动还留着的元素的注释符号：
 *    被删掉的条目注释留在旧位置上，最后会挂到挪进那个位置的元素上。
 * 2. 合并后的条目可能是从 pages.json 读出来的对象，没有内部 `type`
 *    标记（本用例预置的文件就是这样），`type === 'home'` 就永远
 *    找不到目标，重排悄悄地没做。
 * 3. 第一个合并条目需要 `#ifdef` 块时，直接给 `before:0` 赋值会把
 *    GENERATED 标记整个换掉，而不是在它后面补。
 *
 * 平台模型和 concurrent-pages-json.test.ts 一样：当前平台
 * （mp-weixin）从 PageContext 构造函数传进去，预置的文件代表另一个
 * 终端的输出。
 */

function writePage(pagesDir: string, name: string, title: string): void {
  fs.writeFileSync(
    path.join(pagesDir, `${name}.vue`),
    [
      '<script lang="ts" setup>',
      `definePage(() => ({ style: { navigationBarTitleText: '${title}' } }));`,
      '</script>',
      '',
      `<template><div>${title}</div></template>`,
      '',
    ].join('\n'),
    'utf-8',
  )
}

describe('pages.json home page reordering keeps comment attachment', () => {
  let tmpDir: string
  let srcDir: string
  let pagesJsonPath: string

  beforeAll(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'uni-pages-home-reorder-'))
    srcDir = path.join(tmpDir, 'src')
    const pagesDir = path.join(srcDir, 'pages')
    fs.mkdirSync(pagesDir, { recursive: true })

    writePage(pagesDir, 'index', 'home')
    writePage(pagesDir, 'about', 'about')
    writePage(pagesDir, 'settings', 'settings')
    writePage(pagesDir, 'app-only', 'app only')

    pagesJsonPath = path.join(srcDir, 'pages.json')
  })

  beforeEach(() => {
    // 按另一个平台的运行结果预置 pages.json，首页条目放在最后，
    // 逼着合并结果必须重排。首页条目和扫描到的页面内容一致，所以
    // 合并成一条盖住所有已记录平台（APP、H5、MP-WEIXIN）的条目。
    //
    // 第一个合并条目（app-only）只属于部分平台、要包 #ifdef，
    // 以前这会把 before:0 上的 GENERATED 标记整个换掉。
    fs.writeFileSync(
      pagesJsonPath,
      [
        '{',
        '  "pages": [',
        '    // GENERATED BY UNI-PAGES, PLATFORM: H5',
        '    // #ifdef APP',
        '    {',
        '      "path": "pages/app-only",',
        '      "style": {',
        '        "navigationBarTitleText": "app only"',
        '      }',
        '    },',
        '    // #endif',
        '    {',
        '      "path": "pages/about",',
        '      "style": {',
        '        "navigationBarTitleText": "about"',
        '      }',
        '    },',
        '    {',
        '      "path": "pages/settings",',
        '      "style": {',
        '        "navigationBarTitleText": "settings"',
        '      }',
        '    },',
        '    // #ifdef H5 || APP',
        '    {',
        '      "path": "pages/index",',
        '      "style": {',
        '        "navigationBarTitleText": "home"',
        '      }',
        '    }',
        '    // #endif',
        '  ]',
        '}',
      ].join('\n'),
      'utf-8',
    )
  })

  afterAll(() => {
    fs.rmSync(tmpDir, { recursive: true, force: true })
  })

  it('moves home first without stranding comments or overwriting the generation marker', async () => {
    const ctx = new PageContext(
      { dir: 'src/pages', outDir: 'src', homePage: 'pages/index', dts: false },
      tmpDir,
      'mp-weixin',
    )
    await ctx.updatePagesJSON()

    const content = fs.readFileSync(pagesJsonPath, 'utf-8')

    // 合并后的首页条目在 APP、H5 与 MP-WEIXIN 都有，盖住了全部平台，
    // 所以待在下标 0、不用包裹。app-only 与 about/settings 只属于部分
    // 平台，各自留着 #ifdef 块；它们的注释要跟着条目走，不能留在原来
    // 的位置挂到邻居身上；生成标记也必须留在最顶部——哪怕第一个合并
    // 条目（app-only）是包着的。按位置检查完整布局：
    //   marker, pages/index,
    //   #ifdef (app-only), pages/app-only, #endif,
    //   #ifdef (about), pages/about, #endif,
    //   #ifdef (settings), pages/settings, #endif
    const markerPos = content.indexOf('GENERATED BY UNI-PAGES, PLATFORM: APP || H5 || MP-WEIXIN')
    const indexPos = content.indexOf('"pages/index"')
    const appIfdefPos = content.indexOf('#ifdef APP || MP-WEIXIN')
    const appPos = content.indexOf('"pages/app-only"')
    const appEndifPos = content.indexOf('#endif', appIfdefPos)
    const aboutIfdefPos = content.indexOf('#ifdef H5 || MP-WEIXIN')
    const aboutPos = content.indexOf('"pages/about"')
    const aboutEndifPos = content.indexOf('#endif', aboutPos)
    const settingsIfdefPos = content.indexOf('#ifdef H5 || MP-WEIXIN', aboutEndifPos)
    const settingsPos = content.indexOf('"pages/settings"')
    const settingsEndifPos = content.indexOf('#endif', settingsPos)

    expect(markerPos).toBeGreaterThan(-1)
    expect(markerPos).toBeLessThan(indexPos)
    expect(indexPos).toBeLessThan(appIfdefPos)
    expect(appIfdefPos).toBeLessThan(appPos)
    expect(appPos).toBeLessThan(appEndifPos)
    expect(appEndifPos).toBeLessThan(aboutIfdefPos)
    expect(aboutIfdefPos).toBeLessThan(aboutPos)
    expect(aboutPos).toBeLessThan(aboutEndifPos)
    expect(aboutEndifPos).toBeLessThan(settingsIfdefPos)
    expect(settingsIfdefPos).toBeLessThan(settingsPos)
    expect(settingsPos).toBeLessThan(settingsEndifPos)

    // 输出必须仍可解析，且首页是第一个条目。
    const parsed = cjParse(content) as CommentObject
    const pages = parsed.pages
    expect(Array.isArray(pages)).toBe(true)
    if (!Array.isArray(pages)) {
      return
    }
    const paths = pages
      .filter((p): p is CommentObject => typeof p === 'object' && p !== null)
      .map(p => p.path)
    expect(paths).toEqual(['pages/index', 'pages/app-only', 'pages/about', 'pages/settings'])
  })

  it('keeps the output stable across consecutive runs', async () => {
    const ctx = new PageContext(
      { dir: 'src/pages', outDir: 'src', homePage: 'pages/index', dts: false },
      tmpDir,
      'mp-weixin',
    )
    await ctx.updatePagesJSON()
    const first = fs.readFileSync(pagesJsonPath, 'utf-8')

    // 第二次运行读回生成的文件；生成标记必须还能在 before:0 找到，
    // 布局不能变来变去。
    await ctx.updatePagesJSON()
    const second = fs.readFileSync(pagesJsonPath, 'utf-8')

    expect(second).toBe(first)
  })

  it('keeps the #ifdef block of entries behind home intact when home is not last', async () => {
    // 首页在预置文件的中间：把它从数组里挪出来后，comment-json 会把
    // 后面条目的注释往前挪到它的旧位置。所以要先删掉留下来的注释符
    // 号、再挪条目，顺序反了就会弄坏挪进那个位置的条目的
    // #ifdef/#endif。
    fs.writeFileSync(
      pagesJsonPath,
      [
        '{',
        '  "pages": [',
        '    // GENERATED BY UNI-PAGES, PLATFORM: H5',
        '    {',
        '      "path": "pages/about",',
        '      "style": {',
        '        "navigationBarTitleText": "about"',
        '      }',
        '    },',
        '    {',
        '      "path": "pages/index",',
        '      "style": {',
        '        "navigationBarTitleText": "home"',
        '      }',
        '    },',
        '    {',
        '      "path": "pages/settings",',
        '      "style": {',
        '        "navigationBarTitleText": "settings"',
        '      }',
        '    },',
        '    // #ifdef APP',
        '    {',
        '      "path": "pages/app-only",',
        '      "style": {',
        '        "navigationBarTitleText": "app only"',
        '      }',
        '    }',
        '    // #endif',
        '  ]',
        '}',
      ].join('\n'),
      'utf-8',
    )

    const ctx = new PageContext(
      { dir: 'src/pages', outDir: 'src', homePage: 'pages/index', dts: false },
      tmpDir,
      'mp-weixin',
    )
    await ctx.updatePagesJSON()

    const content = fs.readFileSync(pagesJsonPath, 'utf-8')
    // 没有变体盖住全部平台，所以每个条目都包着 #ifdef；首页在自己
    // 的块里挪到最前，app-only 虽然排在首页原来的位置后面，也必须
    // 留着重新算出来的 #ifdef 块。
    const markerPos = content.indexOf('GENERATED BY UNI-PAGES, PLATFORM: APP || H5 || MP-WEIXIN')
    const homeIfdefPos = content.indexOf('#ifdef H5 || MP-WEIXIN')
    const indexPos = content.indexOf('"pages/index"')
    const indexEndifPos = content.indexOf('#endif', indexPos)
    const aboutIfdefPos = content.indexOf('#ifdef H5 || MP-WEIXIN', indexEndifPos)
    const aboutPos = content.indexOf('"pages/about"')
    const aboutEndifPos = content.indexOf('#endif', aboutPos)
    const settingsIfdefPos = content.indexOf('#ifdef H5 || MP-WEIXIN', aboutEndifPos)
    const settingsPos = content.indexOf('"pages/settings"')
    const appIfdefPos = content.indexOf('#ifdef APP || MP-WEIXIN')
    const appPos = content.indexOf('"pages/app-only"')
    const appEndifPos = content.indexOf('#endif', appPos)

    expect(markerPos).toBeGreaterThan(-1)
    expect(markerPos).toBeLessThan(homeIfdefPos)
    expect(homeIfdefPos).toBeLessThan(indexPos)
    expect(indexPos).toBeLessThan(indexEndifPos)
    expect(indexEndifPos).toBeLessThan(aboutIfdefPos)
    expect(aboutIfdefPos).toBeLessThan(aboutPos)
    expect(aboutPos).toBeLessThan(aboutEndifPos)
    expect(aboutEndifPos).toBeLessThan(settingsIfdefPos)
    expect(settingsIfdefPos).toBeLessThan(settingsPos)
    expect(settingsPos).toBeLessThan(appIfdefPos)
    expect(appIfdefPos).toBeLessThan(appPos)
    expect(appPos).toBeLessThan(appEndifPos)

    const parsed = cjParse(content) as CommentObject
    const pages = parsed.pages
    expect(Array.isArray(pages)).toBe(true)
    if (!Array.isArray(pages)) {
      return
    }
    const paths = pages
      .filter((p): p is CommentObject => typeof p === 'object' && p !== null)
      .map(p => p.path)
    expect(paths).toEqual(['pages/index', 'pages/about', 'pages/settings', 'pages/app-only'])
  })

  it('stays stable when platform usage counts tie', async () => {
    // 每个平台集两个条目（2:2 并列）。过去默认平台按 map 插入顺序挑
    // 选，首页重排在两次运行间改变这个顺序，包裹关系来回翻转。平台
    // 全集按构造与顺序无关，因此第二次运行必须字节相同。
    fs.writeFileSync(
      pagesJsonPath,
      [
        '{',
        '  "pages": [',
        '    // GENERATED BY UNI-PAGES, PLATFORM: H5',
        '    // #ifdef H5',
        '    {',
        '      "path": "pages/about",',
        '      "style": {',
        '        "navigationBarTitleText": "about"',
        '      }',
        '    },',
        '    // #endif',
        '    // #ifdef APP',
        '    {',
        '      "path": "pages/index",',
        '      "style": {',
        '        "navigationBarTitleText": "home"',
        '      }',
        '    },',
        '    // #endif',
        '    // #ifdef H5',
        '    {',
        '      "path": "pages/settings",',
        '      "style": {',
        '        "navigationBarTitleText": "settings"',
        '      }',
        '    },',
        '    // #endif',
        '    // #ifdef APP',
        '    {',
        '      "path": "pages/app-only",',
        '      "style": {',
        '        "navigationBarTitleText": "app only"',
        '      }',
        '    }',
        '    // #endif',
        '  ]',
        '}',
      ].join('\n'),
      'utf-8',
    )

    const ctx = new PageContext(
      { dir: 'src/pages', outDir: 'src', homePage: 'pages/index', dts: false },
      tmpDir,
      'mp-weixin',
    )
    await ctx.updatePagesJSON()
    const first = fs.readFileSync(pagesJsonPath, 'utf-8')

    // 基于全集的标记与上一次运行产生的条目顺序无关
    expect(first).toContain('GENERATED BY UNI-PAGES, PLATFORM: APP || H5 || MP-WEIXIN')

    await ctx.updatePagesJSON()
    const second = fs.readFileSync(pagesJsonPath, 'utf-8')
    expect(second).toBe(first)
  })
})
